export function formatMoney(cents: number): string {
  if (!Number.isSafeInteger(cents))
    throw new TypeError('Prices must use integer cents.');
  return new Intl.NumberFormat('en-CA', {
    style: 'currency',
    currency: 'CAD',
    maximumFractionDigits: cents % 100 === 0 ? 0 : 2,
  }).format(cents / 100);
}
